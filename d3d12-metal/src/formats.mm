bool format_needs_pixel_format_view(DXGI_FORMAT format) {
    const auto source = format_info(format);
    for (const auto &view : formats)
        if (view.info.family == source.family && view.info.metal != source.metal) return true;
    return false;
}
FormatInfo format_info(DXGI_FORMAT format) {
    for (const auto &entry : formats) if (entry.format == format) return entry.info;
    return {};
}
